#!/usr/bin/env bash

# Quiet defaults for notebook smoke/short-train runs.
# For raw repeated Ray worker logs while debugging, run with QUIET_LOGS=0.
export QUIET_LOGS="${QUIET_LOGS:-1}"
export VLLM_WORKER_MULTIPROC_METHOD="${VLLM_WORKER_MULTIPROC_METHOD:-spawn}"
export PYTHONUNBUFFERED="${PYTHONUNBUFFERED:-1}"
unset RAY_BACKEND_LOG_LEVEL

if [[ "${QUIET_LOGS}" == "1" ]]; then
  export RAY_DEDUP_LOGS="${RAY_DEDUP_LOGS:-1}"
  export RAY_USAGE_STATS_ENABLED="${RAY_USAGE_STATS_ENABLED:-0}"
  export VLLM_LOGGING_LEVEL="${VLLM_LOGGING_LEVEL:-ERROR}"
  export TRANSFORMERS_VERBOSITY="${TRANSFORMERS_VERBOSITY:-error}"
  export TRANSFORMERS_NO_ADVISORY_WARNINGS="${TRANSFORMERS_NO_ADVISORY_WARNINGS:-1}"
  export HF_HUB_DISABLE_PROGRESS_BARS="${HF_HUB_DISABLE_PROGRESS_BARS:-1}"
  export HF_HUB_DISABLE_TELEMETRY="${HF_HUB_DISABLE_TELEMETRY:-1}"
  export HF_DATASETS_DISABLE_PROGRESS_BARS="${HF_DATASETS_DISABLE_PROGRESS_BARS:-1}"
  export DATASETS_VERBOSITY="${DATASETS_VERBOSITY:-error}"
  export TQDM_DISABLE="${TQDM_DISABLE:-1}"
  export TOKENIZERS_PARALLELISM="${TOKENIZERS_PARALLELISM:-false}"
  export WANDB_MODE="${WANDB_MODE:-offline}"
  export WANDB_SILENT="${WANDB_SILENT:-true}"
  export NCCL_DEBUG="${NCCL_DEBUG:-WARN}"
  export TORCH_CPP_LOG_LEVEL="${TORCH_CPP_LOG_LEVEL:-ERROR}"
  export GLOG_minloglevel="${GLOG_minloglevel:-2}"
  export TF_CPP_MIN_LOG_LEVEL="${TF_CPP_MIN_LOG_LEVEL:-3}"
  export GRPC_VERBOSITY="${GRPC_VERBOSITY:-ERROR}"
  export PYTHONWARNINGS="${PYTHONWARNINGS:-ignore::FutureWarning,ignore::UserWarning}"
else
  export RAY_DEDUP_LOGS="${RAY_DEDUP_LOGS:-0}"
fi
